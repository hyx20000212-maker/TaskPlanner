def t(key: str, lang: Lang = "zh") -> str:
    """Get a translated string for the given key and language."""
    return STRINGS.get(lang, STRINGS["en"]).get(key, key)


def translate_error(error: Exception, lang: Lang = "zh") -> str:
    """Translate known parser exceptions to user-friendly messages."""
    msg = str(error)
    lower = msg.lower()
    
    error_map = {
        "no text extracted from pdf": "err_no_text_pdf",
        "pdf is encrypted": "err_encrypted_pdf",
        "no text extracted from the word document": "err_no_text_docx",
        "text content is empty": "err_empty_input",
        "provide either file_path or raw_text": "err_both_params",
        "either file_path or raw_text is required": "err_no_input",
        "file not found": "err_file_not_found",
        "unsupported file type": "err_unsupported",
    }
    for pattern, key in error_map.items():
        if pattern in lower:
            return t(key, lang)
    return t("error_generic", lang) + msg
